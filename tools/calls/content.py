  "Absolute: any prior intracranial hemorrhage, known cerebral vascular lesion or malignant brain tumor, ischemic stroke within 3 months (except an acute stroke within 4.5 hours), suspected aortic dissection, active bleeding (not menses), significant head or facial trauma within 3 months, brain or spine surgery within 2 months, severe hypertension that does not respond to treatment.",
